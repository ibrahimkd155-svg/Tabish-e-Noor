function getLanguage() {
  const saved = localStorage.getItem("tn-language");
  return ["fa","ps","en"].includes(saved) ? saved : "fa";
}
function applyLanguage(lang) {
  const chosen = translations[lang] ? lang : "fa";
  localStorage.setItem("tn-language", chosen);
  document.documentElement.lang = chosen;
  document.documentElement.dir = chosen === "en" ? "ltr" : "rtl";
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (translations[chosen][key]) el.textContent = translations[chosen][key];
  });
  const switcher = document.getElementById("language-switch");
  if (switcher) switcher.value = chosen;
  const branchId = new URLSearchParams(location.search).get("id") || "1";
  const branchKey = { "1":"branchOne", "2":"branchTwo", "3":"branchThree" }[branchId] || "branchOne";
  const branchTitle = document.getElementById("branch-title");
  if (branchTitle) branchTitle.textContent = translations[chosen][branchKey];
  document.title = chosen === "en" ? "Branch information | Tabish-e-Noor" :
    chosen === "ps" ? "د څانګې معلومات | تابش نور" : "معلومات نمایندگی | مکتب تابش نور";
}
document.addEventListener("DOMContentLoaded", () => {
  document.getElementById("year")?.replaceChildren(document.createTextNode(new Date().getFullYear()));
  const page = document.body.dataset.page;
  if (page === "language") {
    // The language selection screen deliberately starts without forcing a saved language.
    document.querySelectorAll("[data-language]").forEach(button => {
      button.addEventListener("click", () => {
        localStorage.setItem("tn-language", button.dataset.language);
        location.href = "branches.html";
      });
    });
    return;
  }
  applyLanguage(getLanguage());
  document.getElementById("language-switch")?.addEventListener("change", e => {
    applyLanguage(e.target.value);
  });
  document.querySelectorAll("[data-branch]").forEach(link => {
    const lang = getLanguage();
    link.href = `branch.html?id=${link.dataset.branch}&lang=${lang}`;
  });
  // Keep language in branch navigation.
  document.querySelectorAll('a[href="branches.html"]').forEach(link => {
    if (page === "branch") link.href = `branches.html?lang=${getLanguage()}`;
  });
});
